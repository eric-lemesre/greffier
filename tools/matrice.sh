#!/bin/sh
# Matrice de traçabilité (et son inverse) : vue de synthèse, en un seul
# fichier lisible, de ce qu'OpenFastTrace (tools/oft.sh) et la classification
# (tools/classification.sh) établissent déjà séparément — chacun répond à sa
# question, ni l'un ni l'autre ne montre, d'un coup d'œil, PAR OÙ une
# exigence est couverte, ni QUELS fichiers d'outillage ne revendiquent aucune
# exigence. Cet outil n'ajoute AUCUN contrôle et ne fait JAMAIS échouer : il
# rend visible ce que les autres vérifient déjà, rien de plus (cible
# informative, absente de `task ci` / `just ci`).
#
# Deux sections dans docs/tracabilite/matrice.md :
#
#   1. exigences -> couvertures RÉELLES, trouvées par BALAYAGE du dépôt
#      (motif `[<type>->req~…~n]`, même famille de motif qu'OpenFastTrace
#      scanne — R2). Ce ne sont PAS les `Needs:` déclarés, qui peuvent être
#      optimistes ou oubliés : c'est ce qui existe réellement dans le code.
#
#   2. l'inverse — les fichiers d'OUTILLAGE (tools/, hooks, gabarits de forge)
#      qui ne portent AUCUNE trace `->req~…`. C'est une liste DE REVUE, pas un
#      verdict : l'absence de tag ne prouve pas l'absence d'exigence — un
#      test d'intégration, par exemple, peut exercer plusieurs fichiers sans
#      que chacun porte son propre tag. `examples/` et `templates/` en sont
#      exclus : le premier a sa propre spécification autonome, le second ne
#      porte que des identifiants d'exemple (même exclusion qu'OpenFastTrace,
#      tools/oft.sh).
#
# docs/tracabilite/ échappe volontairement à la parité bilingue FR/EN des
# fiches normatives (ADR-0009 s'applique aux artefacts qu'un humain édite ;
# celui-ci se régénère) : seule la LANGUE choisie à l'instanciation
# (LEXIQUE_LANGUE) commande le texte du gabarit, comme docs/audit/README.md
# et docs/todo/README.md.
#
#   sh tools/matrice.sh          # régénère docs/tracabilite/matrice.md
#
# POSIX sh + awk.
set -eu
# Tri en ordre des octets, quelle que soit la locale du poste ou de la CI :
# sinon l'artefact généré sous fr_FR diffère de celui de la CI (C.UTF-8),
# et l'anti-dérive le dit périmé. Les caractères restent ceux de la locale.
unset LC_ALL
export LC_COLLATE=C

# Chemins portant espaces ou métacaractères (constat de revue n° 2) : le
# découpage par défaut d'un « $(git ls-files) » non quoté coupe « mon
# document.md » en deux et laisse un glob s'expanser. Une porte qui rate un
# fichier ne signale rien — elle se contente de ne pas le voir. On découpe
# donc sur les seules fins de ligne, globbing désactivé.
IFS='
'
set -f

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "${ROOT}"
. "${ROOT}/tools/lexique.sh"

[ "${1:-}" = "" ] || { echo "Usage : sh tools/matrice.sh" >&2; exit 2; }

REP="docs/tracabilite"
OUT="${REP}/matrice.md"
mkdir -p "${REP}"

doit="$(lex NORM_DOIT)"
devrait="$(lex NORM_DEVRAIT)"
peut="$(lex NORM_PEUT)"

# --- En-tête ------------------------------------------------------------
# Aucune date de génération : l'historique git la porte déjà (date du commit
# qui modifie ce fichier), et une date IMPRIMÉE dans un artefact généré fait
# échouer l'anti-dérive (tools/derive.sh) un jour sur deux sans aucun
# changement réel à couvrir — défaut constaté à la mise en place de cette
# porte : « régénérer puis comparer » redevient un contrôle qui échoue tout
# seul, exactement l'anti-pattern que R8 interdit (méthode, ch. 4).
if [ "${LEXIQUE_LANGUE}" = "en" ]; then
    {
        printf '%s\n\n' "# Traceability matrix"
        printf '%s\n\n' "<!-- GENERATED by tools/matrice.sh — do not edit by hand (R8). -->"
        printf '%s\n\n' "Summary view, informative only: it adds no control beyond \`task trace\` (OpenFastTrace) or \`task ci\` (\`tools/classification.sh\`), and can never fail a gate. Section 1: every requirement in the specifications, with its REAL coverage found by scanning the repository (not only the declared \`Needs:\`). Section 2: the reverse — tooling files with no traceability tag at all, a review list, not a verdict."
    } > "${OUT}"
else
    {
        printf '%s\n\n' "# Matrice de traçabilité"
        printf '%s\n\n' "<!-- GÉNÉRÉ par tools/matrice.sh — ne pas éditer à la main (R8). -->"
        printf '%s\n\n' "Vue de synthèse, informative : elle n'ajoute aucun contrôle à \`task trace\` (OpenFastTrace) ni à \`task ci\` (\`tools/classification.sh\`) et ne peut jamais faire échouer une porte. Section 1 : chaque exigence des spécifications, avec ses couvertures RÉELLEMENT trouvées par balayage du dépôt (pas seulement les \`Needs:\` déclarés). Section 2 : son inverse, les fichiers d'outillage sans aucune trace de traçabilité — une liste de revue, pas un verdict."
    } > "${OUT}"
fi

# --- Section 1 : exigences -> couvertures --------------------------------

FICHIERS="$(git ls-files 'spec/02-exigences/*.md' 2>/dev/null | \
            grep -v 'spec/02-exigences/README.md' || true)"

if [ "${LEXIQUE_LANGUE}" = "en" ]; then
    printf '%s\n\n' "## 1. Requirements -> coverage" >> "${OUT}"
else
    printf '%s\n\n' "## 1. Exigences → couvertures" >> "${OUT}"
fi

if [ -z "${FICHIERS}" ]; then
    if [ "${LEXIQUE_LANGUE}" = "en" ]; then
        printf '%s\n\n' "No specification found under \`spec/02-exigences/\`." >> "${OUT}"
    else
        printf '%s\n\n' "Aucune spécification trouvée sous \`spec/02-exigences/\`." >> "${OUT}"
    fi
else
    # Couvertures réelles : balayage du même périmètre qu'OpenFastTrace
    # (tools/oft.sh, INPUTS) à la recherche du motif `[<type>->req~…~n]`. Le
    # type n'est PAS une liste fermée (impl/utest/itest/stest/mtest/dsn… selon
    # ce que le projet instancié ajoute) : le motif reste générique, comme
    # celui d'OpenFastTrace, plutôt que d'énumérer des types qui deviendraient
    # vite obsolètes.
    # Exclusion : docs/revues et docs/todo CITENT des exigences pour en
    # parler (constat de revue, fiche de feuille de route), jamais pour les
    # couvrir — une citation qui compterait comme preuve fabriquerait de la
    # couverture. Le reste de docs/ porte des items réels (docs/methode est
    # l'implémentation même de la méthode).
    SCAN_FILES="$(git ls-files spec docs examples src tools .github .gitlab \
                     .gitlab-ci.yml AGENTS.md README.md README.en.md \
                     CONTRIBUTING.md CHANGELOG.md Taskfile.yml 2>/dev/null | \
                  grep -v '^docs/revues/\|^docs/todo/' || true)"
    COUVERTURES=""
    if [ -n "${SCAN_FILES}" ]; then
        # shellcheck disable=SC2086 — découpe en mots voulue.
        COUVERTURES="$(grep -nHoE '\[[a-z]+->req~[a-z0-9-]+~[0-9]+\]' ${SCAN_FILES} 2>/dev/null | awk -F: '
            {
                balise = $0
                sub(/^[^:]*:[^:]*:/, "", balise)
                type = balise; sub(/^\[/, "", type); sub(/->.*$/, "", type)
                id = balise; sub(/^\[[a-z]+->/, "", id); sub(/\]$/, "", id)
                printf "%s\t%s\t%s:%s\n", id, type, $1, $2
            }
        ')"
    fi

    # shellcheck disable=SC2086 — découpe en mots voulue, à l identique de
    # tools/classification.sh.
    awk -v couvertures="${COUVERTURES}" \
        -v doit="${doit}" -v devrait="${devrait}" -v peut="${peut}" \
        -v en="$([ "${LEXIQUE_LANGUE}" = "en" ] && echo 1 || echo 0)" '
        BEGIN {
            n = split(couvertures, lignes, "\n")
            for (i = 1; i <= n; i++) {
                if (lignes[i] == "") continue
                split(lignes[i], champ, "\t")
                cid = champ[1]; ctype = champ[2]; cloc = champ[3]
                nb_couv[cid]++
                liste_couv[cid] = liste_couv[cid] sprintf("  - `%s` — %s\n", ctype, cloc)
            }
        }
        function solder(   niveau, testable) {
            if (id == "") return
            niveau = ""
            if (enonce ~ ("(^|[^A-Za-zÀ-ÿ])(" doit ")([^A-Za-zÀ-ÿ]|$)"))         niveau = "DOIT"
            else if (enonce ~ ("(^|[^A-Za-zÀ-ÿ])(" devrait ")([^A-Za-zÀ-ÿ]|$)")) niveau = "DEVRAIT"
            else if (enonce ~ ("(^|[^A-Za-zÀ-ÿ])(" peut ")([^A-Za-zÀ-ÿ]|$)"))    niveau = "PEUT"
            if (niveau == "") niveau = (en ? "(undetermined — see `task classification`)" \
                                            : "(non déterminé — voir « task classification »)")

            printf "#### `%s`\n\n", id
            printf (en ? "- Normative level: %s\n" : "- Niveau normatif : %s\n"), niveau
            printf "- %s\n", (needs == "" ? (en ? "Needs: (none)" : "Needs : (absent)") : needs)

            # Testable, au sens de tools/classification.sh : seul le DOIT
            # engage une vérification (R10) dans ce format ditem — DEVRAIT et
            # PEUT en sont léquivalent du « non applicable ».
            testable = (niveau == "DOIT")
            if (testable) total_testables++

            if (nb_couv[id] > 0) {
                if (testable) total_couvertes++
                printf (en ? "- Real coverage (%d):\n" : "- Couvertures réelles (%d) :\n"), nb_couv[id]
                printf "%s", liste_couv[id]
            } else if (testable) {
                total_a_couvrir++
                print (en ? "- Real coverage: — TO COVER" : "- Couvertures réelles : — À COUVRIR")
            } else {
                print (en ? "- Real coverage: none (level not required)" \
                          : "- Couvertures réelles : aucune (niveau non exigé)")
            }
            print ""
            id = ""; enonce = ""; needs = ""
        }

        FNR == 1 { solder(); printf "### %s\n\n", FILENAME }

        /^`req~[a-z0-9-]+~[0-9]+`[ \t]*$/ {
            solder()
            id = $0; gsub(/`/, "", id); gsub(/[ \t]/, "", id)
            dans_enonce = 1
            next
        }

        id == "" { next }

        # Espace toléré avant le deux-points (« Needs : » à la française) ;
        # les lignes Needs: se cumulent — la dernière n écrase pas la première.
        /^(Rationale[ ]?:|Covers[ ]?:|Needs[ ]?:|Critères d.acceptation|Acceptance criteria|## )/ {
            dans_enonce = 0
        }
        /^Needs[ ]?:/ { needs = (needs == "" ? $0 : needs " " $0) }
        dans_enonce { enonce = enonce " " $0 }

        END {
            solder()
            print (en ? "### Summary (real coverage)" : "### Bilan (couvertures réelles)")
            print ""
            if (total_testables > 0) {
                if (en) {
                    printf "%d/%d testable requirement(s) covered by at least one real trace (%.1f %%)", \
                           total_couvertes, total_testables, 100 * total_couvertes / total_testables
                    if (total_a_couvrir > 0) printf " — %d to cover", total_a_couvrir
                } else {
                    printf "%d/%d exigence(s) testable(s) couverte(s) par au moins une trace réelle (%.1f %%)", \
                           total_couvertes, total_testables, 100 * total_couvertes / total_testables
                    if (total_a_couvrir > 0) printf " — %d à couvrir", total_a_couvrir
                }
                printf ".\n"
            } else {
                print (en ? "No testable requirement recorded." : "Aucune exigence testable recensée.")
            }
        }
    ' ${FICHIERS} >> "${OUT}"
fi

# --- Section 2 : inverse — outillage sans exigence -----------------------

if [ "${LEXIQUE_LANGUE}" = "en" ]; then
    {
        printf '\n%s\n\n' "## 2. The reverse — tooling without a requirement"
        printf '%s\n\n' "Tooling files (\`tools/\`, git hooks, forge templates) carrying NO traceability tag (\`->req~…\`). **Honest warning**: the absence of a tag does NOT prove the absence of a requirement — a file can very well serve a requirement covered elsewhere. This list is a REVIEW list, not a verdict. \`examples/\` and \`templates/\` are excluded (own specification, or example identifiers only — same exclusion as OpenFastTrace, \`tools/oft.sh\`)."
    } >> "${OUT}"
else
    {
        printf '\n%s\n\n' "## 2. L'inverse — outillage sans exigence"
        printf '%s\n\n' "Fichiers d'outillage (\`tools/\`, hooks git, gabarits de forge) qui ne portent AUCUN tag de traçabilité (\`->req~…\`). **Avertissement honnête** : l'absence de tag ne prouve PAS l'absence d'exigence — un fichier peut très bien servir une exigence couverte ailleurs. Cette liste est une liste DE REVUE, pas un verdict. \`examples/\` et \`templates/\` en sont exclus (spécification propre, ou identifiants d'exemple seulement — même exclusion qu'OpenFastTrace, \`tools/oft.sh\`)."
    } >> "${OUT}"
fi

SOURCES="$(git ls-files tools .githooks .github .gitlab .gitlab-ci.yml 2>/dev/null || true)"

SANS_TRACE=""
TOTAL_SOURCES=0
TOTAL_SANS=0
for f in ${SOURCES}; do
    TOTAL_SOURCES=$((TOTAL_SOURCES + 1))
    if ! grep -qE -- '->req~' "${f}" 2>/dev/null; then
        SANS_TRACE="${SANS_TRACE}${f}
"
        TOTAL_SANS=$((TOTAL_SANS + 1))
    fi
done

if [ "${TOTAL_SANS}" -eq 0 ]; then
    if [ "${LEXIQUE_LANGUE}" = "en" ]; then
        printf '%s\n\n' "No file without a trace among the ${TOTAL_SOURCES} tooling file(s) examined." >> "${OUT}"
    else
        printf '%s\n\n' "Aucun fichier sans trace parmi les ${TOTAL_SOURCES} fichier(s) d'outillage examiné(s)." >> "${OUT}"
    fi
else
    # Regroupement par répertoire IMMÉDIAT (dernier segment du chemin retiré),
    # ordre alphabétique déjà garanti par git ls-files. Un rapprochement par
    # simple PRÉFIXE (« commence par tools/ ») attraperait aussi
    # « tools/hooks/… » sous le groupe « tools » ET sous son propre groupe
    # « tools/hooks » — double compte constaté à la mise en place (bogue
    # analogue à un préfixe « lib/socle » attrapant « lib/socle-extra »,
    # mais par IMBRICATION de répertoires plutôt que par préfixe de nom).
    # L'égalité EXACTE du répertoire immédiat referme ce piège.
    # « . » pour un fichier à la racine (pas de « / ») : cas rare ici
    # (.gitlab-ci.yml, mais déjà tagué aujourd'hui) — traité quand même, pour
    # ne pas dépendre de ce qui se trouve être vrai à l'instant présent.
    dirname_de() { case "$1" in */*) printf '%s' "${1%/*}" ;; *) printf '.' ;; esac; }
    REPERTOIRES=""
    for f in ${SANS_TRACE}; do REPERTOIRES="${REPERTOIRES}$(dirname_de "${f}")
"; done
    REPERTOIRES="$(printf '%s' "${REPERTOIRES}" | sort -u)"
    for d in ${REPERTOIRES}; do
        FICHIERS_DIR="$(printf '%s' "${SANS_TRACE}" | awk -v dir="${d}" '{ f = $0; if (f ~ /\//) sub(/\/[^\/]+$/, "", f); else f = "."; if (f == dir) print }')"
        N=0
        for _ in ${FICHIERS_DIR}; do N=$((N + 1)); done
        printf '### `%s` (%d)\n\n' "${d}" "${N}" >> "${OUT}"
        for ff in ${FICHIERS_DIR}; do
            printf -- '- `%s`\n' "${ff}" >> "${OUT}"
        done
        printf '\n' >> "${OUT}"
    done
    if [ "${LEXIQUE_LANGUE}" = "en" ]; then
        printf '%s\n\n' "**Total: ${TOTAL_SANS}/${TOTAL_SOURCES} tooling file(s) without a traceability trace.**" >> "${OUT}"
    else
        printf '%s\n\n' "**Total : ${TOTAL_SANS}/${TOTAL_SOURCES} fichier(s) d'outillage sans trace de traçabilité.**" >> "${OUT}"
    fi
fi

echo "Matrice de traçabilité : ${OUT}"
